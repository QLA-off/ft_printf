#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	size_t			i;
	unsigned char	*str;

	i = 0;
	str = s;
	while (n > i)
	{
		str[i] = c;
		i++;
	}
	return (str);
}
